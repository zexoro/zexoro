using System.Globalization;
using System.Text;
using Zexoro.Configuration;
using Zexoro.Platforms;

namespace Zexoro.Formats.Nsis;

/// <summary>
/// Generates the NSIS script for an installer (docs/design/0003-mvp.md section 3). The script is
/// written next to the staged files it names (see <see cref="NsisInstallerSpec"/>), and makensis
/// runs in that directory, so every path in it is relative and the text does not depend on the host.
/// </summary>
/// <remarks>
/// Installer exit codes: 0 success, 1 cancelled by the user, 2 aborted (unsupported Windows, or a
/// per-machine install without administrator rights), 3 a newer version is already installed,
/// 4 the application is running or its files are in use.
/// </remarks>
public static class NsisScript
{
    /// <summary>Exit code when a newer version is installed.</summary>
    public const int ExitNewerVersionInstalled = 3;

    /// <summary>Exit code when the application is running or its files are in use.</summary>
    public const int ExitApplicationInUse = 4;

    /// <summary>The longest configuration string the script accepts (NSIS strings hold 1024 characters, including expanded paths).</summary>
    public const int MaxStringLength = 512;

    private const string UninstallKeyPrefix = @"Software\Microsoft\Windows\CurrentVersion\Uninstall\";

    /// <summary>Generates the script text (LF line endings; write it as UTF-8 with a byte order mark).</summary>
    /// <exception cref="NsisException">A value cannot be represented in the installer.</exception>
    public static string Generate(NsisInstallerSpec spec)
    {
        ArgumentNullException.ThrowIfNull(spec);
        Validate(spec);

        var w = new ScriptWriter();
        var name = NsisString.Escape(spec.Name);
        var version = spec.Version.ToString();
        var main = @"$INSTDIR\app\" + NsisString.EscapePath(spec.MainExecutable);
        var mainDirectory = spec.MainExecutable.Contains('/', StringComparison.Ordinal)
            ? @"$INSTDIR\app\" + NsisString.EscapePath(spec.MainExecutable[..spec.MainExecutable.LastIndexOf('/')])
            : @"$INSTDIR\app";
        var machine = spec.Scope == WindowsInstallScope.Machine;
        var context = machine ? "all" : "current";

        w.Line("; Generated by zexoro. Do not edit: 'zexoro pack' writes it again from zexoro.toml.");
        w.Line("Unicode true");
        w.Line("ManifestDPIAware true");
        w.Line("SetCompressor /SOLID lzma");
        w.Line($"RequestExecutionLevel {(machine ? "admin" : "user")}");
        w.Line();
        w.Line($"!define ZX_REGROOT {(machine ? "HKLM" : "HKCU")}");
        w.Line($"!define ZX_UNINSTALL_KEY {NsisString.Quote(UninstallKeyPrefix + spec.AppId)}");
        w.Line($"!define ZX_VERSION_ORDER \"{NsisVersionOrder.Key(spec.Version)}\"");
        w.Line($"!define ZX_MAIN \"{main}\"");
        w.Line($"!define ZX_MAIN_DIR \"{mainDirectory}\"");
        w.Line();
        w.Line(spec.Name.Contains('&', StringComparison.Ordinal)
            ? $"Name \"{name}\" \"{name.Replace("&", "&&", StringComparison.Ordinal)}\""
            : $"Name \"{name}\"");
        w.Line($"OutFile \"{NsisInstallerSpec.OutputFileName}\"");
        w.Line(machine
            ? $"InstallDir \"{(spec.Is64Bit ? "$PROGRAMFILES64" : "$PROGRAMFILES")}\\{name}\""
            : $"InstallDir \"$LOCALAPPDATA\\Programs\\{name}\"");
        w.Line($"BrandingText {NsisString.Quote($"{spec.Name} {version}")}");
        w.Line();
        w.Line("!include MUI2.nsh");
        w.Line("!include LogicLib.nsh");
        w.Line("!include x64.nsh");
        w.Line();
        w.Line($"!define MUI_ICON \"{NsisInstallerSpec.IconFileName}\"");
        w.Line($"!define MUI_UNICON \"{NsisInstallerSpec.IconFileName}\"");
        w.Line("!define MUI_ABORTWARNING");
        if (spec.LicenseFileName is { } license)
        {
            w.Line($"!insertmacro MUI_PAGE_LICENSE \"{NsisString.Escape(license)}\"");
        }

        w.Line("!insertmacro MUI_PAGE_INSTFILES");
        w.Line("!define MUI_FINISHPAGE_RUN");
        w.Line("!define MUI_FINISHPAGE_RUN_FUNCTION zxLaunch");
        w.Line("!insertmacro MUI_PAGE_FINISH");
        w.Line("!insertmacro MUI_UNPAGE_CONFIRM");
        w.Line("!insertmacro MUI_UNPAGE_INSTFILES");
        w.Line("!insertmacro MUI_LANGUAGE \"English\"");
        w.Line();
        var fileVersion = string.Create(CultureInfo.InvariantCulture, $"{spec.Version.Major}.{spec.Version.Minor}.{spec.Version.Patch}.0");
        w.Line("; No LegalCopyright: zexoro has no copyright notice to put there.");
        w.Line("!pragma warning disable 9100");
        w.Line($"VIProductVersion \"{fileVersion}\"");
        w.Line($"VIFileVersion \"{fileVersion}\"");
        w.Line($"VIAddVersionKey /LANG=${{LANG_ENGLISH}} \"ProductName\" \"{name}\"");
        w.Line($"VIAddVersionKey /LANG=${{LANG_ENGLISH}} \"ProductVersion\" {NsisString.Quote(version)}");
        w.Line($"VIAddVersionKey /LANG=${{LANG_ENGLISH}} \"CompanyName\" {NsisString.Quote(spec.Publisher)}");
        w.Line($"VIAddVersionKey /LANG=${{LANG_ENGLISH}} \"FileDescription\" {NsisString.Quote($"{spec.Name} installer")}");
        w.Line($"VIAddVersionKey /LANG=${{LANG_ENGLISH}} \"FileVersion\" {NsisString.Quote(version)}");
        if (spec.SignCommand is { } sign)
        {
            w.Line();
            w.Line("; Sign the uninstaller before it is embedded, and the installer once it is written.");
            w.Line($"!uninstfinalize `{sign}` = 0");
            w.Line($"!finalize `{sign}` = 0");
        }

        w.Line();
        w.Line("; Refuses to continue while the main executable is running: a running image cannot be opened for writing.");
        w.Line("!macro ZX_CHECK_NOT_RUNNING UN");
        w.Line("Function ${UN}zxCheckNotRunning");
        w.Line("  retry:");
        w.Line("  ${If} ${FileExists} \"${ZX_MAIN}\"");
        w.Line("    ClearErrors");
        w.Line("    FileOpen $0 \"${ZX_MAIN}\" a");
        w.Line("    ${If} ${Errors}");
        w.Line($"      MessageBox MB_RETRYCANCEL|MB_ICONEXCLAMATION \"{name} is running. Close it, then select Retry.\" /SD IDCANCEL IDRETRY retry");
        w.Line($"      SetErrorLevel {ExitApplicationInUse}");
        w.Line("      Quit");
        w.Line("    ${EndIf}");
        w.Line("    FileClose $0");
        w.Line("  ${EndIf}");
        w.Line("FunctionEnd");
        w.Line("!macroend");
        w.Line("!insertmacro ZX_CHECK_NOT_RUNNING \"\"");
        w.Line("!insertmacro ZX_CHECK_NOT_RUNNING \"un.\"");
        w.Line();
        w.Line("Function .onInit");
        WriteArchitectureCheck(w, spec, name);
        if (spec.Is64Bit)
        {
            w.Line("  SetRegView 64");
        }

        w.Line($"  SetShellVarContext {context}");
        if (machine)
        {
            WriteAdminCheck(w, name);
        }

        w.Line("  ; An existing install is upgraded in place, wherever it is.");
        w.Line("  ReadRegStr $0 ${ZX_REGROOT} \"${ZX_UNINSTALL_KEY}\" \"InstallLocation\"");
        w.Line("  ${If} $0 != \"\"");
        w.Line("    StrCpy $INSTDIR $0");
        w.Line($"    ReadRegStr $1 ${{ZX_REGROOT}} \"${{ZX_UNINSTALL_KEY}}\" \"{NsisVersionOrder.RegistryValueName}\"");
        w.Line("    ${If} $1 != \"\"");
        w.Line("      StrCpy $2 \"${ZX_VERSION_ORDER}\"");
        w.Line("      System::Call 'kernel32::CompareStringOrdinal(w r1, i -1, w r2, i -1, i 0) i .r3'");
        w.Line("      ${If} $3 = 3");
        w.Line("        ReadRegStr $4 ${ZX_REGROOT} \"${ZX_UNINSTALL_KEY}\" \"DisplayVersion\"");
        w.Line($"        MessageBox MB_OK|MB_ICONSTOP \"{name} $4 is already installed, which is newer than this version ({NsisString.Escape(version)}). Uninstall it first to install an older version.\" /SD IDOK");
        w.Line($"        SetErrorLevel {ExitNewerVersionInstalled}");
        w.Line("        Quit");
        w.Line("      ${EndIf}");
        w.Line("    ${EndIf}");
        w.Line("  ${EndIf}");
        w.Line("FunctionEnd");
        w.Line();
        w.Line("Function un.onInit");
        if (spec.Is64Bit)
        {
            w.Line("  SetRegView 64");
        }

        w.Line($"  SetShellVarContext {context}");
        if (machine)
        {
            WriteAdminCheck(w, name);
        }

        w.Line("FunctionEnd");
        w.Line();
        w.Line("; Moves the previous version aside and deletes it, so no stale files remain.");
        w.Line("Function zxRemoveApp");
        w.Line("  RMDir /r \"$INSTDIR\\app.old\"");
        w.Line("  ${If} ${FileExists} \"$INSTDIR\\app\\*.*\"");
        w.Line("    retry:");
        w.Line("    ClearErrors");
        w.Line("    Rename \"$INSTDIR\\app\" \"$INSTDIR\\app.old\"");
        w.Line("    ${If} ${Errors}");
        w.Line($"      MessageBox MB_RETRYCANCEL|MB_ICONEXCLAMATION \"Files in $INSTDIR\\app are in use. Close {name}, then select Retry.\" /SD IDCANCEL IDRETRY retry");
        w.Line($"      SetErrorLevel {ExitApplicationInUse}");
        w.Line("      Quit");
        w.Line("    ${EndIf}");
        w.Line("    RMDir /r \"$INSTDIR\\app.old\"");
        w.Line("  ${EndIf}");
        w.Line("FunctionEnd");
        w.Line();
        w.Line("Function zxLaunch");
        w.Line("  SetOutPath \"${ZX_MAIN_DIR}\"");
        w.Line(machine
            ? "  ; The installer runs elevated; Explorer starts the application as the signed-in user."
            : "  ; The installer runs as the user, so the application starts as the user.");
        w.Line(machine
            ? "  Exec '\"$WINDIR\\explorer.exe\" \"${ZX_MAIN}\"'"
            : "  Exec '\"${ZX_MAIN}\"'");
        w.Line("FunctionEnd");
        w.Line();
        w.Line("Section \"-Install\"");
        w.Line("  Call zxCheckNotRunning");
        w.Line("  Call zxRemoveApp");
        w.Line("  SetOutPath \"$INSTDIR\\app\"");
        w.Line($"  File /r \"{NsisInstallerSpec.AppDirectoryName}\\*\"");
        foreach (var directory in spec.EmptyDirectories)
        {
            w.Line($"  CreateDirectory \"$INSTDIR\\app\\{NsisString.EscapePath(directory)}\"");
        }

        w.Line("  SetOutPath \"$INSTDIR\"");
        w.Line($"  File \"{NsisInstallerSpec.InstallRecordFileName}\"");
        w.Line($"  WriteUninstaller \"$INSTDIR\\{NsisInstallerSpec.UninstallerFileName}\"");
        w.Line("  ; Shortcuts of a previous version are replaced by the configured ones.");
        WriteShortcutDeletion(w, name);
        w.Line("  SetOutPath \"${ZX_MAIN_DIR}\"");
        if (spec.Shortcuts.HasFlag(WindowsShortcuts.StartMenu))
        {
            w.Line($"  CreateShortcut \"$SMPROGRAMS\\{name}.lnk\" \"${{ZX_MAIN}}\"");
        }

        if (spec.Shortcuts.HasFlag(WindowsShortcuts.Desktop))
        {
            w.Line($"  CreateShortcut \"$DESKTOP\\{name}.lnk\" \"${{ZX_MAIN}}\"");
        }

        w.Line("  SetOutPath \"$INSTDIR\"");
        WriteRegStr(w, "DisplayName", $"\"{name}\"");
        WriteRegStr(w, "DisplayVersion", NsisString.Quote(version));
        WriteRegStr(w, "Publisher", NsisString.Quote(spec.Publisher));
        WriteRegStr(w, "DisplayIcon", $"\"$INSTDIR\\{NsisInstallerSpec.UninstallerFileName},0\"");
        WriteRegStr(w, "InstallLocation", "\"$INSTDIR\"");
        WriteRegStr(w, "UninstallString", $"\"$\\\"$INSTDIR\\{NsisInstallerSpec.UninstallerFileName}$\\\"\"");
        WriteRegStr(w, "QuietUninstallString", $"\"$\\\"$INSTDIR\\{NsisInstallerSpec.UninstallerFileName}$\\\" /S\"");
        if (spec.Url is { } url)
        {
            WriteRegStr(w, "URLInfoAbout", NsisString.Quote(url.ToString()));
        }

        if (spec.Description is { } description)
        {
            WriteRegStr(w, "Comments", NsisString.Quote(description));
        }

        WriteRegStr(w, NsisVersionOrder.RegistryValueName, "\"${ZX_VERSION_ORDER}\"");
        w.Line("  WriteRegDWORD ${ZX_REGROOT} \"${ZX_UNINSTALL_KEY}\" \"NoModify\" 1");
        w.Line("  WriteRegDWORD ${ZX_REGROOT} \"${ZX_UNINSTALL_KEY}\" \"NoRepair\" 1");
        w.Line(string.Create(CultureInfo.InvariantCulture, $"  WriteRegDWORD ${{ZX_REGROOT}} \"${{ZX_UNINSTALL_KEY}}\" \"EstimatedSize\" {Math.Min(spec.EstimatedSizeKb, uint.MaxValue)}"));
        w.Line("SectionEnd");
        w.Line();
        w.Line("Section \"Uninstall\"");
        w.Line("  Call un.zxCheckNotRunning");
        WriteShortcutDeletion(w, name);
        w.Line("  ; Only what the installer and the updater create is removed; the root itself only when it is empty.");
        w.Line("  RMDir /r \"$INSTDIR\\app\"");
        w.Line("  RMDir /r \"$INSTDIR\\app.old\"");
        w.Line("  RMDir /r \"$INSTDIR\\app.new\"");
        w.Line($"  Delete \"$INSTDIR\\{NsisInstallerSpec.InstallRecordFileName}\"");
        w.Line("  Delete \"$INSTDIR\\zexoro-updater.exe\"");
        w.Line($"  Delete \"$INSTDIR\\{NsisInstallerSpec.UninstallerFileName}\"");
        w.Line("  RMDir \"$INSTDIR\"");
        w.Line("  DeleteRegKey ${ZX_REGROOT} \"${ZX_UNINSTALL_KEY}\"");
        WriteUninstallRemove(w, spec, context);
        w.Line("SectionEnd");
        return w.ToString();
    }

    private static void Validate(NsisInstallerSpec spec)
    {
        void Check(string what, string? value)
        {
            if (value is null)
            {
                return;
            }

            if (value.Length > MaxStringLength)
            {
                throw new NsisException($"{what} is longer than {MaxStringLength} characters, which the Windows installer cannot hold.");
            }

            if (value.Contains('\0', StringComparison.Ordinal))
            {
                throw new NsisException($"{what} contains a NUL character.");
            }
        }

        Check("app.id", spec.AppId);
        Check("app.name", spec.Name);
        Check("app.publisher", spec.Publisher);
        Check("app.description", spec.Description);
        Check("app.url", spec.Url?.ToString());
        Check("app.version", spec.Version.ToString());
        Check("input.main", spec.MainExecutable);
        foreach (var path in spec.UninstallRemove)
        {
            Check("windows.uninstall.remove", path);
        }

        foreach (var path in spec.EmptyDirectories)
        {
            Check("an input directory path", path);
        }

        if (spec.Architecture != Architecture.X86 && !spec.Is64Bit)
        {
            throw new NsisException($"Windows installers support x86, x64 and arm64 applications, not {spec.Architecture}.");
        }

        try
        {
            NsisVersionOrder.Key(spec.Version);
        }
        catch (ArgumentException ex)
        {
            throw new NsisException(ex.Message, ex);
        }

        if (spec.SignCommand is { } sign
            && (sign.Contains('`', StringComparison.Ordinal) || sign.Contains("${", StringComparison.Ordinal)
                || sign.Contains("$%", StringComparison.Ordinal) || sign.Any(char.IsControl)))
        {
            throw new ArgumentException("The sign command contains characters makensis would interpret.", nameof(spec));
        }
    }

    private static void WriteArchitectureCheck(ScriptWriter w, NsisInstallerSpec spec, string name)
    {
        string? condition = null;
        string? requirement = null;
        if (spec.Architecture == Architecture.X64)
        {
            condition = "${RunningX64}";
            requirement = "64-bit Windows (x64, or arm64 with x64 emulation)";
        }
        else if (spec.Architecture == Architecture.Arm64)
        {
            condition = "${IsNativeARM64}";
            requirement = "Windows on arm64";
        }

        if (condition is null)
        {
            return;
        }

        w.Line($"  ${{IfNot}} {condition}");
        w.Line($"    MessageBox MB_OK|MB_ICONSTOP \"{name} requires {requirement}.\" /SD IDOK");
        w.Line("    Abort");
        w.Line("  ${EndIf}");
    }

    private static void WriteAdminCheck(ScriptWriter w, string name)
    {
        w.Line("  UserInfo::GetAccountType");
        w.Line("  Pop $0");
        w.Line("  ${If} $0 != \"admin\"");
        w.Line($"    MessageBox MB_OK|MB_ICONSTOP \"{name} is installed for all users, which requires administrator rights.\" /SD IDOK");
        w.Line("    Abort");
        w.Line("  ${EndIf}");
    }

    private static void WriteShortcutDeletion(ScriptWriter w, string name)
    {
        w.Line($"  Delete \"$SMPROGRAMS\\{name}.lnk\"");
        w.Line($"  Delete \"$DESKTOP\\{name}.lnk\"");
    }

    private static void WriteRegStr(ScriptWriter w, string valueName, string quotedValue) =>
        w.Line($"  WriteRegStr ${{ZX_REGROOT}} \"${{ZX_UNINSTALL_KEY}}\" \"{valueName}\" {quotedValue}");

    private static void WriteUninstallRemove(ScriptWriter w, NsisInstallerSpec spec, string scopeContext)
    {
        if (spec.UninstallRemove.Count == 0)
        {
            return;
        }

        w.Line("  ; [windows.uninstall] remove");
        string? current = null;
        foreach (var path in spec.UninstallRemove)
        {
            var (context, target) = MapUninstallPath(path);
            if (context != current)
            {
                w.Line($"  SetShellVarContext {context}");
                current = context;
            }

            w.Line($"  RMDir /r \"{target}\"");
            w.Line($"  Delete \"{target}\"");
        }

        if (current != scopeContext)
        {
            w.Line($"  SetShellVarContext {scopeContext}");
        }
    }

    /// <summary>Maps a <c>remove</c> entry to the shell variable context and the escaped NSIS path.</summary>
    internal static (string Context, string Path) MapUninstallPath(string path)
    {
        var normalized = path.Replace('/', '\\');
        (string Token, string Context, string Variable)[] roots =
        [
            ("%LOCALAPPDATA%", "current", "$LOCALAPPDATA"),
            ("%APPDATA%", "current", "$APPDATA"),

            // NSIS has no ProgramData constant; $APPDATA in the all-users context is ProgramData.
            ("%PROGRAMDATA%", "all", "$APPDATA"),
        ];
        foreach (var (token, context, variable) in roots)
        {
            if (normalized.StartsWith(token + "\\", StringComparison.OrdinalIgnoreCase))
            {
                var rest = normalized[(token.Length + 1)..].TrimEnd('\\');
                return (context, variable + "\\" + NsisString.Escape(rest));
            }
        }

        throw new NsisException($"windows.uninstall.remove: '{path}' must start with %LOCALAPPDATA%, %APPDATA% or %PROGRAMDATA%.");
    }

    private sealed class ScriptWriter
    {
        private readonly StringBuilder _text = new();

        public void Line(string line = "") => _text.Append(line).Append('\n');

        public override string ToString() => _text.ToString();
    }
}
